// Role-aware status LOV: hide BD-stage planning (BD/Renewal Planning) from
// users who can't view BD, and ISG-stage outcomes (ISG Planning, Won) from
// users who can't view ISG. Active/Lost are role-neutral. Unrestricted users
// (both true) see all.
export const filterStatusOptionsByRole = (
  options: { value: string; label: string }[],
  canViewBD: boolean,
  canViewISG: boolean
): { value: string; label: string }[] =>
  options.filter((option) => {
    if (
      (option.value === BD_PLANNING || option.value === RENEWAL_PLANNING) &&
      !canViewBD
    ) {
      return false;
    }
    if ((option.value === ISG_PLANNING || option.value === WON) && !canViewISG) {
      return false;
    }
    return true;
  });

