--- Localization Report Fields Table ---
CREATE TABLE IF NOT EXISTS public.localization_report_fields (
    id SERIAL PRIMARY KEY,
    field_key VARCHAR NOT NULL,
    data_type VARCHAR NOT NULL,
    required BOOLEAN NOT NULL,
    active BOOLEAN NOT NULL,
    entity_type VARCHAR(30),
    description VARCHAR(200),
    create_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    meta_data JSONB,
    CONSTRAINT localization_report_fields_data_type_check CHECK (
        data_type IN ('string', 'date', 'number', 'float')
    )
);

--- Localization Report Fields Country Map Table ---
CREATE TABLE IF NOT EXISTS public.localization_report_fields_country_map (
    id SERIAL PRIMARY KEY,
    country_id INTEGER NOT NULL,
    regulatory_key_id INTEGER NOT NULL,
    report_section VARCHAR NOT NULL,
    activity_section VARCHAR NOT NULL,
    display_order INTEGER NOT NULL,
    field_label VARCHAR NOT NULL,
    field_alias VARCHAR NOT NULL,
    field_value VARCHAR NOT NULL,
    status VARCHAR NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    meta_data JSONB,
    CONSTRAINT localization_report_fields_country_map_regulatory_key_id_fkey FOREIGN KEY (regulatory_key_id) REFERENCES public.localization_report_fields (id) ON UPDATE NO ACTION ON DELETE NO ACTION,
    CONSTRAINT localization_report_fields_country_map_country_id_fkey FOREIGN KEY (country_id) REFERENCES public.localization_country (id) ON UPDATE NO ACTION ON DELETE NO ACTION
);

